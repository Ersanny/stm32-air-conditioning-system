/* ================================================
 * SSD1306'ya komut gonder (static ? sadece bu dosya)
 * ================================================ */
static I2C_Status SSD1306_SendCommand(uint8_t cmd)
{
    if (I2C_Start()                          != I2C_OK) return I2C_TIMEOUT;
    if (I2C_WriteAddress(SSD1306_I2C_ADDR)  != I2C_OK) { I2C_Stop(); return I2C_TIMEOUT; }
    if (I2C_WriteByte(SSD1306_CMD_MODE)     != I2C_OK) { I2C_Stop(); return I2C_TIMEOUT; }
    if (I2C_WriteByte(cmd)                  != I2C_OK) { I2C_Stop(); return I2C_TIMEOUT; }
    I2C_Stop();
    return I2C_OK;
}

/* ================================================
 * SSD1306_Init ? Ekrani baslat, buffer'i sifirla
 * ================================================ */
void SSD1306_Init(void)
{
		for (volatile uint32_t i = 0; i < 500000; i++);  /* ~100ms @ 8MHz */
    I2C_Init();
    SSD1306_SendCommand(0xAE);   /* Ekrani kapat        */
    SSD1306_SendCommand(0x20);   /* Memory mode         */
    SSD1306_SendCommand(0x00);   /* Horizontal mode     */
    SSD1306_SendCommand(0xB0);   /* Sayfa baslangici    */
    SSD1306_SendCommand(0xC8);   /* COM tarama yonu     */
    SSD1306_SendCommand(0x00);   /* Alt sutun adresi    */
    SSD1306_SendCommand(0x10);   /* Ust sutun adresi    */
    SSD1306_SendCommand(0x40);   /* Baslangic satiri    */
    SSD1306_SendCommand(0x81);   /* Kontrast ayari      */
    SSD1306_SendCommand(0xFF);   /* Maksimum kontrast   */
    SSD1306_SendCommand(0xA1);   /* Segment yonu        */
    SSD1306_SendCommand(0xA6);   /* Normal goruntu      */
    SSD1306_SendCommand(0xA8);   /* Multiplex orani     */
    SSD1306_SendCommand(0x3F);   /* 64 satir            */
    SSD1306_SendCommand(0xA4);   /* RAM'den goster      */
    SSD1306_SendCommand(0xD3);   /* Display offset      */
    SSD1306_SendCommand(0x00);   /* Offset yok          */
    SSD1306_SendCommand(0xD5);   /* Clock bolucu        */
    SSD1306_SendCommand(0xF0);   /* Maksimum frekans    */
    SSD1306_SendCommand(0xD9);   /* On sarj periyodu    */
    SSD1306_SendCommand(0x22);   /* Faz 1-2             */
    SSD1306_SendCommand(0xDA);   /* COM pin yapisi      */
    SSD1306_SendCommand(0x12);   /* Alternatif COM      */
    SSD1306_SendCommand(0xDB);   /* VCOMH seviyesi      */
    SSD1306_SendCommand(0x20);   /* 0.77xVcc            */
    SSD1306_SendCommand(0x8D);   /* Sarj pompasi        */
    SSD1306_SendCommand(0x14);   /* Sarj pompasini ac   */
    SSD1306_SendCommand(0xAF);   /* Ekrani ac           */

    memset(framebuffer, 0, sizeof(framebuffer));
}

/* ================================================
 * SSD1306_Clear ? Frame buffer'i temizle
 * Ekrana yansimaz; Flush() cagrilmasi gerekir
 * ================================================ */
void SSD1306_Clear(void)
{
    memset(framebuffer, 0, sizeof(framebuffer));
}

/* ================================================
 * SSD1306_SetCursor ? Kursor konumunu ayarla
 * ================================================ */
void SSD1306_SetCursor(uint8_t page, uint8_t col)
{
    cursor_page = page;
    cursor_col  = col;
}

/* ================================================
 * SSD1306_WriteChar ? Tek karakter buffer'a yaz (5x8)
 * ================================================ */
void SSD1306_WriteChar(char c)
{
    if (c < '0' || c > '9') return;   /* fontOS16 sadece rakamlari destekler */
    uint8_t index = c - '0';

    /* Karakter 12 piksel yuksek -> 2 sayfaya yayilir */
    uint8_t start_col = cursor_col;
    for (uint8_t i = 0; i < 10; i++)
    {
        if ((start_col + i) < SSD1306_COLS)
        {
            framebuffer[cursor_page][start_col + i]     = fontOS16[index][i];
            if (cursor_page + 1 < SSD1306_PAGES)
                framebuffer[cursor_page + 1][start_col + i] = fontOS16[index][i + 10];
        }
    }
    cursor_col += 10;
    /* Karakter arasi 1 piksel bosluk */
    if (cursor_col < SSD1306_COLS)
    {
        framebuffer[cursor_page][cursor_col]     = 0x00;
        if (cursor_page + 1 < SSD1306_PAGES)
            framebuffer[cursor_page + 1][cursor_col] = 0x00;
        cursor_col++;
    }
}

/* ================================================
 * SSD1306_WriteString ? String buffer'a yaz
 * ================================================ */
void SSD1306_WriteString(const char *str)
{
    while (*str)
        SSD1306_WriteChar(*str++);
}

/* ================================================
 * SSD1306_DrawBitmap ? Tam ekran bitmap'i buffer'a kopyala
 * ================================================ */
void SSD1306_DrawBitmap(const uint8_t *bitmap)
{
    memcpy(framebuffer, bitmap, SSD1306_PAGES * SSD1306_COLS);
}

/* ================================================
 * SSD1306_DrawBigDigit ? 18x32 buyuk rakam buffer'a yaz
 * digit : 0-9
 * x     : sutun baslangici (0-127)
 * page  : sayfa baslangici (0-4, 4 sayfa kaplar)
 * ================================================ */
void SSD1306_DrawBigDigit(uint8_t digit, uint8_t x, uint8_t page)
{
    if (digit > 9) return;
    const uint8_t *glyph = font18x32[digit];

    for (uint8_t p = 0; p < 4; p++)
    {
        for (uint8_t col = 0; col < 18; col++)
        {
            if ((x + col) < SSD1306_COLS)
                framebuffer[page + p][x + col] = glyph[p * 18 + col];
        }
    }
}

/* ================================================
 * SSD1306_Flush ? Buffer'i ekrana gonder
 * Her sayfa icin tek I2C transaction kullanilir
 * ================================================ */
I2C_Status SSD1306_Flush(void)
{
    for (uint8_t page = 0; page < SSD1306_PAGES; page++)
    {
        if (SSD1306_SendCommand(0xB0 + page) != I2C_OK) return I2C_TIMEOUT;
        if (SSD1306_SendCommand(0x00)        != I2C_OK) return I2C_TIMEOUT;
        if (SSD1306_SendCommand(0x10)        != I2C_OK) return I2C_TIMEOUT;

        if (I2C_Start()                         != I2C_OK) return I2C_TIMEOUT;
        if (I2C_WriteAddress(SSD1306_I2C_ADDR)  != I2C_OK) { I2C_Stop(); return I2C_TIMEOUT; }
        if (I2C_WriteByte(SSD1306_DATA_MODE)    != I2C_OK) { I2C_Stop(); return I2C_TIMEOUT; }
        for (uint8_t col = 0; col < SSD1306_COLS; col++)
        {
            if (I2C_WriteByte(framebuffer[page][col]) != I2C_OK) { I2C_Stop(); return I2C_TIMEOUT; }
        }
        I2C_Stop();
    }
    return I2C_OK;
}

/* ================================================
 * SSD1306_WriteNumber ? Sayiyi kucuk fontla buffer'a yaz
 * ================================================ */
static void SSD1306_WriteNumber(uint8_t num)
{
    char buf[4];
    uint8_t i = 0;

    if (num == 0)
    {
        SSD1306_WriteChar('0');
        return;
    }
    while (num > 0)
    {
        buf[i++] = '0' + (num % 10);
        num /= 10;
    }
    while (i > 0)
        SSD1306_WriteChar(buf[--i]);
}
/* ================================================
 * Basit gecikme (busy-wait, ~1ms @ 8MHz HSI)
 * ================================================ */
static void splash_delay_ms(uint16_t ms)
{
    for (uint16_t i = 0; i < ms; i++)
        for (volatile uint16_t j = 0; j < 1000; j++);
}

/* ================================================
 * Logo'yu (x, page) konumuna ciz
 * x ekran disinda olabilir (negatif veya >128) - clipping yapilir
 * ================================================ */
static void draw_logo(int16_t x, uint8_t start_page)
{
    for (uint8_t p = 0; p < 3; p++)
    {
        for (uint8_t col = 0; col < 24; col++)
        {
            int16_t xx = x + col;
            if (xx >= 0 && xx < SSD1306_COLS)
                framebuffer[start_page + p][xx] = github_logo[p][col];
        }
    }
}

/* ================================================
 * "Ersanny" yazisini (x, page) konumuna ciz
 * ================================================ */
static void draw_ersanny(int16_t x, uint8_t start_page)
{
    for (uint8_t p = 0; p < 2; p++)
    {
        for (uint8_t col = 0; col < ERSANNY_WIDTH; col++)
        {
            int16_t xx = x + col;
            if (xx >= 0 && xx < SSD1306_COLS)
                framebuffer[start_page + p][xx] = ersanny_text[p][col];
        }
    }
}

/* ================================================
 * SSD1306_Splash  Acilis animasyonu
 *   - Logo soldan, yazi sagdan kayarak gelir
 *   - Ortada 1.5 saniye durur
 *   - Sag/sol disari kayarak gider
 * ================================================ */
I2C_Status SSD1306_Splash(void)
{
    /* Yerlesim:
     *   Logo + 6px bosluk + "Ersanny" = 24 + 6 + 62 = 92 px
     *   Yatay ortali baslangic: x = (128 - 92) / 2 = 18
     *   Logo final x = 18, page 2 (y=16..39)
     *   Yazi final x = 18 + 24 + 6 = 48, page 3 (y=24..39)
     */
    const int16_t LOGO_FINAL_X    = 18;
    const int16_t TEXT_FINAL_X    = 48;
    const uint8_t LOGO_PAGE       = 2;
    const uint8_t TEXT_PAGE       = 3;

    /* === FAZ 1: Slide-in (~400ms) === */
    for (int16_t step = 0; step <= 20; step++)
    {
        int16_t logo_x = -30 + (LOGO_FINAL_X + 30) * step / 20;
        int16_t text_x = 130 - (130 - TEXT_FINAL_X) * step / 20;

        SSD1306_Clear();
        draw_logo(logo_x, LOGO_PAGE);
        draw_ersanny(text_x, TEXT_PAGE);
        if (SSD1306_Flush() != I2C_OK) return I2C_TIMEOUT;
        splash_delay_ms(20);
    }

    /* === FAZ 2: Sabit dur (~1500ms) === */
    splash_delay_ms(100500);

    /* === FAZ 3: Slide-out (~400ms) === */
    for (int16_t step = 0; step <= 20; step++)
    {
        int16_t logo_x = LOGO_FINAL_X - (LOGO_FINAL_X + 30) * step / 20;
        int16_t text_x = TEXT_FINAL_X + (130 - TEXT_FINAL_X) * step / 20;

        SSD1306_Clear();
        draw_logo(logo_x, LOGO_PAGE);
        draw_ersanny(text_x, TEXT_PAGE);
        if (SSD1306_Flush() != I2C_OK) return I2C_TIMEOUT;
        splash_delay_ms(20);
    }

    SSD1306_Clear();
    return SSD1306_Flush();
}

/* ================================================
 * SSD1306_DrawUI ? Tum arayuzu guncelle ve ekrana gonder
 * set_temp  : SET sicaklik (buyuk font, ortada)
 * room_temp : Oda sicakligi (kucuk font, sag alt)
 * fan_pct   : Fan hizi %   (kucuk font, sol alt)
 * ================================================ */
I2C_Status SSD1306_DrawUI(uint8_t set_temp, uint8_t room_temp, uint8_t fan_pct)
{
    /* Modu sicaklik farkindan otomatik hesapla */
    KlimaMod mod;
    if      (room_temp > set_temp) mod = KLIMA_MOD_SOGUTMA;
    else if (room_temp < set_temp) mod = KLIMA_MOD_ISITMA;
    else                           mod = KLIMA_MOD_BEKLEME;

    /* Katman 1: moda gore bitmap'i buffer'a kopyala */
    SSD1306_DrawBitmap(ui_bitmaps[mod]);

    /* Katman 2: SET sicaklik -- buyuk font, ortada
     * Digit alani merkezi x=65, her rakam 18px, aralarinda 4px bosluk
     * Tek haneli : tek rakam x=56 (merkeze hizali)
     * Cift haneli: onlar x=45, birler x=67                           */
    if (set_temp < 10)
    {
        SSD1306_DrawBigDigit(set_temp, 56, 0);
    }
    else
    {
        SSD1306_DrawBigDigit(set_temp / 10, 45, 0);
        SSD1306_DrawBigDigit(set_temp % 10, 67, 0);
    }

    /* Katman 3: Oda sicakligi -- kucuk font, sag alt */
    SSD1306_SetCursor(6, 77);    // sag alt - oda sicakligi
    SSD1306_WriteNumber(room_temp);

    /* Katman 4: Fan hizi -- kucuk font, sol alt */
		SSD1306_SetCursor(6, 20);    // sol alt - fan
    SSD1306_WriteNumber(fan_pct);

    /* Tek seferde ekrana gonder, sonucu caller'a ilet */
    return SSD1306_Flush();
}
